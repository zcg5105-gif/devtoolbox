export default {
  name: 'IdCardParser',
  data() {
    return {
      idNumber: '',
      batchText: '',
      batchResults: [],
      showLunar: false
    }
  },
  computed: {
    normalizedId() {
      return this.normalizeId(this.idNumber)
    },
    singleResult() {
      return this.parseIdCard(this.normalizedId)
    },
    detailItems() {
      return [
        { label: '是否有效', value: this.singleResult.valid ? '有效' : '无效', className: this.singleResult.valid ? 'is-valid' : 'is-invalid' },
        { label: '出生日期', value: this.singleResult.birthDateText },
        { label: '年龄', value: this.singleResult.ageText },
        { label: '性别', value: this.singleResult.gender },
        { label: '省份/城市/区县', value: this.singleResult.addressText },
        { label: '地区码', value: this.singleResult.areaCodeText },
        { label: '顺序码', value: this.singleResult.sequenceCode },
        { label: '校验码验证', value: this.singleResult.checksumText, className: this.singleResult.checksumValid ? 'is-valid' : 'is-invalid' },
        { label: '农历生日', value: this.lunarBirthdayText }
      ]
    },
    lunarBirthdayText() {
      if (!this.showLunar) {
        return '未开启'
      }

      if (!this.singleResult.birthDate) {
        return '-'
      }

      return this.formatLunarDate(this.singleResult.birthDate)
    },
    batchSummary() {
      if (!this.batchResults.length) {
        return '0 条'
      }

      const validCount = this.batchResults.filter(item => item.valid).length
      return `共 ${this.batchResults.length} 条，有效 ${validCount} 条`
    },
    weightsText() {
      return CHECKSUM_WEIGHTS.join(', ')
    },
    checksumMapText() {
      return CHECKSUM_CODES.join(', ')
    },
    checksumStatusText() {
      if (!this.idNumber) {
        return '-'
      }

      if (this.singleResult.checksumValid === null) {
        return '无法计算'
      }

      return this.singleResult.checksumValid ? '通过' : '不通过'
    }
  },
  mounted() {
    this.generateTestId(false)
  },
  methods: {
    validateSingle() {
      if (!this.idNumber) {
        this.$message.warning('请输入身份证号码')
        return
      }

      if (this.singleResult.valid) {
        this.$message.success('身份证号码验证通过')
      } else {
        this.$message.error(this.singleResult.errors[0] || '身份证号码无效')
      }
    },
    parseIdCard(value) {
      const normalized = this.normalizeId(value)
      const errors = []
      const result = {
        idNumber: normalized,
        valid: false,
        errors,
        areaCode: normalized.slice(0, 6),
        area: null,
        areaExact: false,
        addressText: '-',
        areaCodeText: '-',
        birthDate: null,
        birthDateText: '-',
        age: null,
        ageText: '-',
        gender: '-',
        sequenceCode: normalized.slice(14, 17) || '-',
        expectedCheckCode: '',
        actualCheckCode: normalized.slice(17, 18),
        checksumValid: null,
        checksumText: '-',
        summary: '请输入 18 位身份证号码'
      }

      if (!normalized) {
        return result
      }

      if (!/^\d{17}[\dX]$/.test(normalized)) {
        errors.push('格式必须为 17 位数字加 1 位数字或 X')
      }

      const area = this.resolveArea(normalized.slice(0, 6))
      result.area = area
      result.areaExact = area.exact
      result.addressText = area.text
      result.areaCodeText = area.exact ? `${result.areaCode}（精确匹配）` : `${result.areaCode}（仅匹配到${area.level}）`

      if (!area.valid) {
        errors.push('地区码不在内置数据库中')
      }

      const birthDate = this.parseBirthDate(normalized.slice(6, 14))
      if (birthDate) {
        result.birthDate = birthDate
        result.birthDateText = this.formatDate(birthDate)
        result.age = this.calculateAge(birthDate)
        result.ageText = `${result.age} 岁`
      } else {
        errors.push('出生日期无效或超出范围')
      }

      if (/^\d{17}/.test(normalized)) {
        const sequence = Number(normalized.slice(14, 17))
        result.gender = sequence % 2 === 1 ? '男' : '女'
        result.expectedCheckCode = this.calculateCheckCode(normalized.slice(0, 17))
      }

      if (result.expectedCheckCode && result.actualCheckCode) {
        result.checksumValid = result.expectedCheckCode === result.actualCheckCode
        result.checksumText = result.checksumValid
          ? `通过（${result.actualCheckCode}）`
          : `不通过，应为 ${result.expectedCheckCode}`

        if (!result.checksumValid) {
          errors.push('最后一位校验码不正确')
        }
      }

      result.valid = errors.length === 0
      result.summary = result.valid
        ? `${result.addressText}，${result.birthDateText}，${result.gender}`
        : errors[0]

      return result
    },
    normalizeId(value) {
      return String(value || '').replace(/\s/g, '').toUpperCase()
    },
    resolveArea(code) {
      const exact = AREA_CODE_DATABASE[code]

      if (exact) {
        return {
          valid: true,
          exact: true,
          level: exact.length >= 3 ? '区县' : exact.length === 2 ? '城市' : '省份',
          parts: exact,
          text: exact.join(' / ')
        }
      }

      const cityCode = `${code.slice(0, 4)}00`
      const city = AREA_CODE_DATABASE[cityCode]
      if (city) {
        return {
          valid: true,
          exact: false,
          level: '城市',
          parts: city,
          text: `${city.join(' / ')} / 未收录区县`
        }
      }

      const provinceCode = `${code.slice(0, 2)}0000`
      const province = AREA_CODE_DATABASE[provinceCode]
      if (province) {
        return {
          valid: false,
          exact: false,
          level: '省份',
          parts: province,
          text: `${province[0]} / 未收录城市 / 未收录区县`
        }
      }

      return {
        valid: false,
        exact: false,
        level: '地区码',
        parts: [],
        text: '未知地区'
      }
    },
    parseBirthDate(value) {
      if (!/^\d{8}$/.test(value)) {
        return null
      }

      const year = Number(value.slice(0, 4))
      const month = Number(value.slice(4, 6))
      const day = Number(value.slice(6, 8))
      const date = new Date(year, month - 1, day)

      if (
        date.getFullYear() !== year ||
        date.getMonth() + 1 !== month ||
        date.getDate() !== day
      ) {
        return null
      }

      const minDate = new Date(`${MIN_BIRTHDAY}T00:00:00`)
      const today = new Date()
      today.setHours(0, 0, 0, 0)

      if (date < minDate || date > today) {
        return null
      }

      return date
    },
    calculateAge(date) {
      const today = new Date()
      let age = today.getFullYear() - date.getFullYear()
      const hadBirthday = today.getMonth() > date.getMonth() ||
        (today.getMonth() === date.getMonth() && today.getDate() >= date.getDate())

      if (!hadBirthday) {
        age -= 1
      }

      return age
    },
    calculateCheckCode(prefix17) {
      if (!/^\d{17}$/.test(prefix17)) {
        return ''
      }

      const sum = prefix17
        .split('')
        .reduce((total, digit, index) => total + Number(digit) * CHECKSUM_WEIGHTS[index], 0)

      return CHECKSUM_CODES[sum % 11]
    },
    formatDate(date) {
      const pad = value => String(value).padStart(2, '0')
      return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`
    },
    generateTestId(showMessage = true) {
      const availableCodes = Object.keys(AREA_CODE_DATABASE).filter(code => code.endsWith('00') === false)
      const areaCode = availableCodes[this.randomInt(0, availableCodes.length - 1)]
      const year = this.randomInt(1960, 2004)
      const month = this.randomInt(1, 12)
      const maxDay = new Date(year, month, 0).getDate()
      const day = this.randomInt(1, maxDay)
      const birth = `${year}${this.pad(month)}${this.pad(day)}`
      const sequence = String(this.randomInt(1, 999)).padStart(3, '0')
      const prefix = `${areaCode}${birth}${sequence}`

      this.idNumber = `${prefix}${this.calculateCheckCode(prefix)}`

      if (showMessage) {
        this.$message.success('已生成测试用身份证号')
      }
    },
    validateBatch() {
      const items = this.batchText
        .split(/\r\n|\r|\n/)
        .map(item => this.normalizeId(item))
        .filter(Boolean)

      this.batchResults = items.map((item, index) => ({
        ...this.parseIdCard(item),
        index
      }))

      if (!items.length) {
        this.$message.warning('请先输入批量身份证号码')
      }
    },
    loadBatchSample() {
      const first = this.idNumber || this.createTestId('110105', '19900101', '123')
      const second = this.createTestId('440305', '19880808', '246')
      const invalid = `${second.slice(0, 17)}9`

      this.batchText = [first, second, invalid].join('\n')
      this.validateBatch()
    },
    createTestId(areaCode, birth, sequence) {
      const prefix = `${areaCode}${birth}${sequence}`
      return `${prefix}${this.calculateCheckCode(prefix)}`
    },
    clearAll() {
      this.idNumber = ''
      this.batchText = ''
      this.batchResults = []
    },
    clearBatch() {
      this.batchText = ''
      this.batchResults = []
    },
    randomInt(min, max) {
      if (window.crypto && window.crypto.getRandomValues) {
        const value = new Uint32Array(1)
        window.crypto.getRandomValues(value)
        return min + (value[0] % (max - min + 1))
      }

      return min + Math.floor(Math.random() * (max - min + 1))
    },
    pad(value) {
      return String(value).padStart(2, '0')
    },
    async copySingleResult() {
      await this.copyText(JSON.stringify(this.singleResult, null, 2))
    },
    async copyBatchResult() {
      const text = this.batchResults
        .map(item => `${item.idNumber}\t${item.valid ? '有效' : '无效'}\t${item.valid ? item.summary : item.errors.join('；')}`)
        .join('\n')

      await this.copyText(text)
    },
    async copyText(text) {
      try {
        await navigator.clipboard.writeText(text)
        this.$message.success('已复制')
      } catch (error) {
        this.copyWithFallback(text)
        this.$message.success('已复制')
      }
    },
    copyWithFallback(text) {
      const textarea = document.createElement('textarea')
      textarea.value = text
      textarea.setAttribute('readonly', '')
      textarea.style.position = 'fixed'
      textarea.style.left = '-9999px'
      document.body.appendChild(textarea)
      textarea.select()
      document.execCommand('copy')
      document.body.removeChild(textarea)
    },
    formatLunarDate(date) {
      const lunar = this.solarToLunar(date)

      if (!lunar) {
        return '仅支持 1900-2100 年'
      }

      const leapText = lunar.isLeap ? '闰' : ''
      return `${lunar.year}年 ${leapText}${LUNAR_MONTHS[lunar.month - 1]}${LUNAR_DAYS[lunar.day - 1]}`
    },
    solarToLunar(date) {
      const baseDate = new Date(1900, 0, 31)
      const year = date.getFullYear()

      if (year < 1900 || year > 2100) {
        return null
      }

      let offset = Math.floor((date - baseDate) / 86400000)
      if (offset < 0) {
        return null
      }

      let lunarYear = 1900
      let yearDays = this.lunarYearDays(lunarYear)

      while (offset >= yearDays && lunarYear < 2100) {
        offset -= yearDays
        lunarYear += 1
        yearDays = this.lunarYearDays(lunarYear)
      }

      const leapMonth = this.lunarLeapMonth(lunarYear)
      let isLeap = false
      let lunarMonth = 1
      let monthDays = this.lunarMonthDays(lunarYear, lunarMonth)

      while (offset >= monthDays && lunarMonth <= 12) {
        offset -= monthDays

        if (leapMonth === lunarMonth && !isLeap) {
          isLeap = true
        } else {
          if (isLeap) {
            isLeap = false
          }
          lunarMonth += 1
        }

        monthDays = isLeap
          ? this.lunarLeapDays(lunarYear)
          : this.lunarMonthDays(lunarYear, lunarMonth)
      }

      return {
        year: lunarYear,
        month: lunarMonth,
        day: offset + 1,
        isLeap
      }
    },
    lunarYearDays(year) {
      let sum = 348
      const info = LUNAR_INFO[year - 1900]

      for (let mask = 0x8000; mask > 0x8; mask >>= 1) {
        if (info & mask) {
          sum += 1
        }
      }

      return sum + this.lunarLeapDays(year)
    },
    lunarLeapMonth(year) {
      return LUNAR_INFO[year - 1900] & 0xf
    },
    lunarLeapDays(year) {
      if (!this.lunarLeapMonth(year)) {
        return 0
      }

      return (LUNAR_INFO[year - 1900] & 0x10000) ? 30 : 29
    },
    lunarMonthDays(year, month) {
      return (LUNAR_INFO[year - 1900] & (0x10000 >> month)) ? 30 : 29
    }
  }
}
